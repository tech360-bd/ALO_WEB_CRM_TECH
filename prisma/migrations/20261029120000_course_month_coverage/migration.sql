-- Additive 13-month official-source coverage. Existing catalogue records are
-- untouched; staged rows are never public until Super Admin approval.
CREATE TABLE `course_month_coverage` (
  `id` VARCHAR(191) NOT NULL,
  `courseId` VARCHAR(191) NOT NULL,
  `calendarMonth` CHAR(7) NOT NULL,
  `campus` VARCHAR(80) NOT NULL DEFAULT '',
  `studyMode` VARCHAR(32) NOT NULL DEFAULT '',
  `qualification` VARCHAR(191) NOT NULL DEFAULT '',
  `availabilityStatus` VARCHAR(191) NOT NULL DEFAULT 'VERIFICATION_PENDING',
  `startDate` DATETIME(3) NULL,
  `applicationOpenDate` DATETIME(3) NULL,
  `applicationCloseDate` DATETIME(3) NULL,
  `internationalDeadline` DATETIME(3) NULL,
  `tuitionAmount` DOUBLE NULL,
  `tuitionCurrency` VARCHAR(191) NOT NULL DEFAULT '',
  `feeAcademicYear` VARCHAR(191) NOT NULL DEFAULT '',
  `feePeriod` VARCHAR(191) NOT NULL DEFAULT '',
  `feeStudentCategory` VARCHAR(191) NOT NULL DEFAULT '',
  `applicationFeeAmount` DOUBLE NULL,
  `applicationFeeCurrency` VARCHAR(191) NOT NULL DEFAULT '',
  `depositAmount` DOUBLE NULL,
  `depositCurrency` VARCHAR(191) NOT NULL DEFAULT '',
  `scholarshipDetails` LONGTEXT NULL,
  `academicRequirements` LONGTEXT NULL,
  `bangladeshRequirements` LONGTEXT NULL,
  `englishRequirements` LONGTEXT NULL,
  `additionalRequirements` LONGTEXT NULL,
  `internationalEligibility` VARCHAR(191) NOT NULL DEFAULT 'NOT_PUBLISHED',
  `feeStatus` VARCHAR(191) NOT NULL DEFAULT 'NOT_PUBLISHED',
  `deadlineStatus` VARCHAR(191) NOT NULL DEFAULT 'NOT_PUBLISHED',
  `scholarshipStatus` VARCHAR(191) NOT NULL DEFAULT 'NOT_PUBLISHED',
  `sourceUrls` LONGTEXT NOT NULL DEFAULT (_utf8mb4'[]'),
  `fieldEvidence` LONGTEXT NOT NULL DEFAULT (_utf8mb4'{}'),
  `sourcePublishedAt` DATETIME(3) NULL,
  `collectedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `lastVerifiedAt` DATETIME(3) NULL,
  `confidence` DOUBLE NOT NULL DEFAULT 0,
  `contentHash` VARCHAR(191) NOT NULL DEFAULT '',
  `evidenceText` LONGTEXT NULL,
  `approvalStatus` VARCHAR(191) NOT NULL DEFAULT 'PENDING',
  `approvedBy` VARCHAR(191) NULL,
  `approvedAt` DATETIME(3) NULL,
  `rejectedBy` VARCHAR(191) NULL,
  `rejectedAt` DATETIME(3) NULL,
  `reviewNotes` TEXT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  UNIQUE INDEX `course_month_coverage_identity` (`courseId`, `calendarMonth`, `campus`, `studyMode`),
  INDEX `course_month_coverage_calendarMonth_availabilityStatus_idx` (`calendarMonth`, `availabilityStatus`),
  INDEX `course_month_coverage_approvalStatus_calendarMonth_idx` (`approvalStatus`, `calendarMonth`),
  INDEX `course_month_coverage_courseId_approvalStatus_idx` (`courseId`, `approvalStatus`),
  PRIMARY KEY (`id`),
  CONSTRAINT `course_month_coverage_courseId_fkey` FOREIGN KEY (`courseId`) REFERENCES `CrmCourse` (`courseId`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `course_month_coverage_versions` (
  `id` VARCHAR(191) NOT NULL,
  `coverageId` VARCHAR(191) NOT NULL,
  `version` INTEGER NOT NULL,
  `action` VARCHAR(191) NOT NULL,
  `snapshot` LONGTEXT NOT NULL,
  `sourceHash` VARCHAR(191) NOT NULL DEFAULT '',
  `actorId` VARCHAR(191) NOT NULL DEFAULT '',
  `notes` TEXT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE INDEX `course_month_coverage_versions_coverageId_version_key` (`coverageId`, `version`),
  INDEX `course_month_coverage_versions_createdAt_idx` (`createdAt`),
  PRIMARY KEY (`id`),
  CONSTRAINT `course_month_coverage_versions_coverageId_fkey` FOREIGN KEY (`coverageId`) REFERENCES `course_month_coverage` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
