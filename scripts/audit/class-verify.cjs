#!/usr/bin/env node
/**
 * Utility-class verification (redesign QA).
 *
 * Tailwind silently drops classes it cannot generate, so a typo or an invented
 * token produces no build error — it just renders unstyled. This script:
 *   1. compiles src/app/globals.css with @tailwindcss/postcss,
 *   2. reads every `className="…"` string in src/**\/*.tsx,
 *   3. strips responsive/state variants (md:, hover:, dark:, group-hover:, …),
 *   4. reports tokens that do not appear in the compiled CSS.
 *
 * Run from the repo root: node scripts/audit/class-verify.cjs
 */
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');
const tailwind = require('@tailwindcss/postcss');

const input = path.resolve('src/app/globals.css');

function escapeClass(cls) {
  // Tailwind escapes selectors; normalise both sides to compare.
  return cls.replace(/[.:/[\]()%,#'"!*+~=<>&|$^{}?@]/g, '\\$&');
}

function collectClassNames() {
  const found = new Map(); // token -> Set(files)
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== 'node_modules') walk(p);
        continue;
      }
      if (!/\.(tsx|ts)$/.test(entry.name)) continue;
      const src = fs.readFileSync(p, 'utf8');
      // className="…", className={`…`}, className={'…'} and className={cn('…', …)}
      const re = /className=(?:"([^"]*)"|\{`([^`]*)`\}|\{"([^"]*)"\})/g;
      let m;
      while ((m = re.exec(src))) {
        let value = m[1] || m[2] || m[3] || '';
        // drop ${…} expressions and quoted string literals inside them
        value = value.replace(/\$\{[^}]*\}/g, ' ');
        for (let token of value.split(/\s+/)) {
          token = token.trim();
          if (!token) continue;
          token = token.split(':').pop();
          if (!token || token.length > 80) continue;
          if (!/^[-a-z0-9_./[\]%#&*+~|^@]+$/.test(token)) continue;
          if (token.endsWith(']') === false && token.includes('[')) continue;
          if (!found.has(token)) found.set(token, new Set());
          found.get(token).add(p);
        }
      }
    }
  };
  walk('src');
  return found;
}

// Classes that intentionally have no generated rule:
//   alo-rich-text  — styled by an inline <style> block in alo/ui.tsx
//   toaster        — runtime hook class used by sonner
//   is-active      — state marker read by tests, not by CSS
const ALLOWLIST = new Set(['alo-rich-text', 'toaster', 'is-active']);

async function main() {
  const css = fs.readFileSync(input, 'utf8');
  const result = await postcss([tailwind()]).process(css, { from: input });
  const compiled = result.css;

  const tokens = collectClassNames();
  const missing = [];
  for (const [token, files] of tokens) {
    // Tailwind escapes selector characters and prefixes variants, so look for the
    // escaped token anywhere in the output rather than as a standalone selector.
    if (compiled.includes(escapeClass(token)) || compiled.includes(token)) continue;
    if (ALLOWLIST.has(token)) continue;
    missing.push({ token, sample: [...files][0] });
  }

  missing.sort((a, b) => a.token.localeCompare(b.token));
  console.log(`checked ${tokens.size} unique class tokens against ${(compiled.length / 1024).toFixed(0)} KB of compiled CSS`);
  console.log(`not generated by Tailwind: ${missing.length}`);
  for (const { token, sample } of missing) console.log(`  ${token}   (${sample})`);
  if (missing.length > 0) process.exitCode = 1;
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
