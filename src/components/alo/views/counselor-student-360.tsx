// CommentComposer — posts either student-visible or internal comment
// ============================================================
function CommentComposer({
  kind,
  studentId,
  onPosted,
  onError,
}: {
  kind: "student" | "internal";
  studentId: string;
  onPosted: () => void;
  onError: (msg: string) => void;
}) {
  const [body, setBody] = React.useState("");
  const [visibility, setVisibility] = React.useState("INTERNAL_ONLY");
  const [commentType, setCommentType] = React.useState("COUNSELOR_NOTE");
  const [posting, setPosting] = React.useState(false);

  const isInternal = kind === "internal";

  const handleSubmit = async () => {
    if (!body.trim()) return;
    setPosting(true);
    try {
      const payload: Record<string, unknown> = {
        type: kind,
        body: body.trim(),
      };
      if (isInternal) {
        payload.visibility = visibility;
        payload.commentType = commentType;
      }
      const res = await fetch(`/api/counselor/students/${encodeURIComponent(studentId)}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(payload),
      });
      const json = await res.json();
      if (json.comment) {
        setBody("");
        onPosted();
      } else {
        onError(json.error ?? "Please try again.");
      }
    } catch (e) {
      onError("Network error — please retry.");
    } finally {
      setPosting(false);
    }
  };

  return (
    <div className={`mt-4 rounded-xl border-2 p-3 ${isInternal ? "border-amber-200 bg-amber-50/30" : "border-[var(--alo-border)] bg-[var(--alo-brand-pale)]/30"}`}>
      <Label htmlFor={`composer-${kind}`} className="mb-1.5 flex items-center gap-1.5 text-xs font-semibold uppercase tracking-wide text-muted-foreground">
        <Icon name={isInternal ? "Lock" : "MessageSquarePlus"} className="size-3.5" />
        {isInternal ? "Add internal note (staff-only)" : "Add student-visible comment"}
      </Label>
      <Textarea
        id={`composer-${kind}`}
        value={body}
        onChange={(e) => setBody(e.target.value)}
        placeholder={
          isInternal
            ? "e.g. Student considering UK vs Canada. Finance verified. Risk: medium (study gap of 3 years)."
            : "e.g. Hi Mehedi — your IELTS mock is scheduled for Saturday. Please bring your passport copy."
        }
        rows={3}
        className="resize-none border-border/60 bg-white text-sm"
      />
      {isInternal && (
        <div className="mt-2 grid gap-2 sm:grid-cols-2">
          <div>
            <Label className="mb-1 block text-[11px] font-medium uppercase text-muted-foreground">Visibility</Label>
            <Select value={visibility} onValueChange={setVisibility}>
              <SelectTrigger className="h-9 text-xs">
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                {Object.entries(VISIBILITY_LABELS).map(([v, l]) => (
                  <SelectItem key={v} value={v} className="text-xs">{l}</SelectItem>
                ))}
              </SelectContent>
            </Select>
          </div>
          <div>
            <Label className="mb-1 block text-[11px] font-medium uppercase text-muted-foreground">Comment type</Label>
            <Select value={commentType} onValueChange={setCommentType}>
              <SelectTrigger className="h-9 text-xs">
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                {Object.entries(COMMENT_TYPE_LABELS).map(([v, l]) => (
                  <SelectItem key={v} value={v} className="text-xs">{l}</SelectItem>
                ))}
              </SelectContent>
            </Select>
          </div>
        </div>
      )}
      <div className="mt-2 flex items-center justify-between gap-2">
        <p className={`text-[11px] ${isInternal ? "text-amber-700" : "text-[var(--alo-brand)]"}`}>
          {isInternal ? (
            <span className="flex items-center gap-1"><Icon name="ShieldAlert" className="size-3" /> Audit-logged. Student will NOT see this.</span>
          ) : (
            <span className="flex items-center gap-1"><Icon name="Eye" className="size-3" /> Visible in student's portal inbox.</span>
          )}
        </p>
        <Button
 size="sm"
 disabled={!body.trim() || posting}
 onClick={handleSubmit}
 className={
 isInternal
 ? " bg-amber-600 text-white hover:bg-amber-700"
 : " bg-[var(--alo-brand)] text-white hover:bg-[var(--alo-brand)]/90"
 }
 >
          {posting ? <Icon name="Loader2" className="mr-1.5 size-3.5 animate-spin" /> : <Icon name="Send" className="mr-1.5 size-3.5" />}
          {isInternal ? "Post Note" : "Post Comment"}
        </Button>
      </div>
    </div>
  );
}

