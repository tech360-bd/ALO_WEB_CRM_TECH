export function CounselorStudent360({ slug, onNavigate = () => {} }: { slug?: string; onNavigate?: (v: ViewKey, slug?: string) => void }) {
  const { toast } = useToast();
  const [students, setStudents] = React.useState<StudentListItem[]>([]);
  const [selectedId, setSelectedId] = React.useState<string>("");
  const [detail, setDetail] = React.useState<StudentDetailResponse | null>(null);
  const [loadingList, setLoadingList] = React.useState(true);
  const [loadingDetail, setLoadingDetail] = React.useState(false);

  // Fetch student list
  React.useEffect(() => {
    let alive = true;
    (async () => {
      setLoadingList(true);
      try {
        const res = await fetch("/api/counselor/students");
        const data = await res.json();
        if (!alive) return;
        const list: StudentListItem[] = data.students ?? [];
        setStudents(list);
        // A slug from the URL always wins. If it is not in this counselor's
        // list we still select the requested id and let the detail endpoint
        // enforce assignment — silently showing the first student instead
        // would display a different student's record.
        if (slug) {
          const match = list.find((s) => s.id === slug || s.studentId === slug);
          setSelectedId(match ? match.id : slug);
        } else if (list.length > 0) {
          setSelectedId(list[0].id);
        }
      } catch {
        if (alive) {
          toast({
            title: "Failed to load students",
            description: "Could not fetch your assigned student list.",
            variant: "destructive",
          });
        }
      } finally {
        if (alive) setLoadingList(false);
      }
    })();
    return () => { alive = false; };
  }, [slug, toast]);

  // Fetch detail when selectedId changes
  const fetchDetail = React.useCallback(async (id: string) => {
    setLoadingDetail(true);
    setDetail(null);
    try {
      const res = await fetch(`/api/counselor/students/${encodeURIComponent(id)}`);
      const data = await res.json();
      if (data.student) {
        setDetail(data);
      } else {
        toast({
          title: "Could not load student detail",
          description: data.error ?? "Please try again.",
          variant: "destructive",
        });
      }
    } catch {
      toast({
        title: "Network error",
        description: "Failed to fetch student detail.",
        variant: "destructive",
      });
    } finally {
      setLoadingDetail(false);
    }
  }, [toast]);

  React.useEffect(() => {
    if (!selectedId) return;
    fetchDetail(selectedId);
  }, [selectedId, fetchDetail]);

  if (loadingList) {
    return <LoadingGrid count={6} />;
  }

  if (students.length === 0) {
    return (
      <div className="space-y-6">
        <EmptyState
          icon="Users"
          title="No students assigned"
          description="You don't have any students assigned yet. Add a lead in CRM to get started."
          action={
            <Button onClick={() => onNavigate("crm")} className="h-11 bg-[var(--alo-cta)] text-white hover:bg-[var(--alo-cta)]/90">
              <Icon name="UserPlus" className="mr-2 size-4" /> Go to CRM
            </Button>
          }
        />
      </div>
    );
  }

  return (
    <div className="space-y-6">
      {/* STUDENT SELECTOR */}
      <Card className="rounded-2xl border-2 border-[var(--alo-brand)]/15">
        <CardContent className="flex flex-col gap-3 pt-5 sm:flex-row sm:items-center">
          <div className="flex items-center gap-2 text-sm font-medium text-muted-foreground">
            <Icon name="Search" className="size-4" />
            Select student:
          </div>
          <Select value={selectedId} onValueChange={setSelectedId}>
            <SelectTrigger className="h-10 flex-1 rounded-xl border-[var(--alo-brand)]/15">
              <SelectValue placeholder="Pick a student" />
            </SelectTrigger>
            <SelectContent>
              {students.map((s) => (
                <SelectItem key={s.id} value={s.id}>
                  <span className="font-mono text-xs text-muted-foreground">{s.studentId}</span>
                  {" — "}
                  <span className="font-medium">{s.fullName}</span>
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
          <Badge variant="outline" className="h-10 border-[var(--alo-brand)]/20 px-3 text-xs">
            {students.findIndex((s) => s.id === selectedId) + 1} of {students.length}
          </Badge>
        </CardContent>
      </Card>

      {loadingDetail || !detail ? (
        <LoadingGrid count={4} />
      ) : (
        <StudentDetailBody detail={detail} onNavigate={onNavigate} refetch={() => fetchDetail(selectedId)} />
      )}
    </div>
  );
}

