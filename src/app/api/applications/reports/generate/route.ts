import { z } from 'zod';
import { db } from '@/lib/db';
import { NextResponse } from 'next/server';
import { withAuth, logAuditAction } from '@/lib/auth-middleware';
import { canViewB2B, canViewB2BCommission, stripB2BFields } from '@/lib/application-manager/service';

const schema = z.object({
  format: z.enum(['json', 'csv', 'xlsx', 'pdf']).default('json'),
  filters: z.object({
    source: z.string().max(191).optional(),
    country: z.string().max(191).optional(),
    from: z.string().datetime().optional(),
    to: z.string().datetime().optional(),
  }).strict().default({}),
  includeB2B: z.boolean().default(false),
}).strict();

function canExport(roles: string[], permissions: string[]): boolean {
  const normalizedRoles = roles.map((role) => role.toLowerCase());
  return normalizedRoles.some((role) => ['super_admin', 'application_manager'].includes(role)) ||
    permissions.includes('application.export') || permissions.includes('application.view_reports');
}

export const POST = withAuth(async (req, auth) => {
  if (!canExport(auth.roles, auth.permissions)) return NextResponse.json({ success: false, error: 'Forbidden: application export permission required.' }, { status: 403 });
  const parsed = schema.safeParse(await req.json().catch(() => null));
  if (!parsed.success) return NextResponse.json({ success: false, error: 'Invalid report request.', details: parsed.error.flatten() }, { status: 400 });
  const { format, filters, includeB2B } = parsed.data;
  const hasB2BAccess = canViewB2B(auth.roles, auth.permissions);
  if (includeB2B && !hasB2BAccess) {
    return NextResponse.json({ success: false, error: 'Forbidden: B2B export requires application.view_b2b permission.' }, { status: 403 });
  }
  if (filters.source?.toUpperCase().startsWith('B2B_') && !hasB2BAccess) {
    return NextResponse.json({ success: false, error: 'Forbidden: B2B reporting requires application.view_b2b permission.' }, { status: 403 });
  }

  const where: Record<string, any> = {};
  if (filters.source) where.applicationSource = filters.source;
  if (filters.country) where.country = filters.country;
  if (filters.from || filters.to) {
    where.createdAt = {};
    if (filters.from) where.createdAt.gte = new Date(filters.from);
    if (filters.to) where.createdAt.lte = new Date(filters.to);
  }

  try {
    const applications = await db.application.findMany({ where, take: 5000, orderBy: { createdAt: 'desc' } });
    const includeB2BForThisReport = includeB2B && hasB2BAccess;
    const canViewCommission = includeB2BForThisReport && canViewB2BCommission(auth.roles, auth.permissions);
    const data = includeB2BForThisReport
      ? applications.map((application: any) => stripB2BFields(application, true, canViewCommission))
      : applications.map((application: any) => stripB2BFields(application, false, false));

    const reportData = {
      format,
      generatedAt: new Date().toISOString(),
      generatedBy: auth.userId,
      filters,
      total: data.length,
      data,
      canViewB2B: includeB2BForThisReport,
    };
    const report = await db.visaReport.create({
      data: {
        reportType: 'application_manager',
        generatedBy: auth.userId,
        generatedByName: auth.name,
        filters: JSON.stringify(filters),
        data: JSON.stringify(reportData).substring(0, 10000),
        format,
        status: 'ready',
      },
    }).catch(() => null);

    await logAuditAction(auth, 'GENERATE_APPLICATION_REPORT', 'Application', report?.id || 'report', { format, filters, includeB2B: includeB2BForThisReport, total: data.length });
    return NextResponse.json({
      success: true,
      data: reportData,
      reportId: report?.id || null,
      downloadUrl: report ? `/api/applications/reports/generate?reportId=${encodeURIComponent(report.id)}&format=${format}` : null,
      delivery: 'JSON_RESPONSE_ONLY',
      message: report ? 'Report data prepared; file export formats are not generated by this endpoint yet.' : 'Report data prepared; report storage is currently unavailable.',
    });
  } catch (error) {
    console.error('[application-report.generate] failed', { error: error instanceof Error ? error.name : 'UnknownError' });
    return NextResponse.json({ success: false, error: 'Application report could not be generated.' }, { status: 503 });
  }
});

export const GET = withAuth(async (req, auth) => {
  const { searchParams } = new URL(req.url);
  const reportId = searchParams.get('reportId');
  const format = searchParams.get('format') || 'json';
  if (!reportId || reportId.length > 191) return NextResponse.json({ success: false, error: 'Valid reportId required.' }, { status: 400 });

  try {
    const report = await db.visaReport.findUnique({ where: { id: reportId } });
    if (!report || report.reportType !== 'application_manager') return NextResponse.json({ success: false, error: 'Report not found.' }, { status: 404 });
    const roles = auth.roles.map((role) => role.toLowerCase());
    const hasGlobalReportAccess = roles.some((role) => ['super_admin', 'application_manager'].includes(role)) || auth.permissions.includes('application.view_reports');
    if (report.generatedBy !== auth.userId && !hasGlobalReportAccess) {
      return NextResponse.json({ success: false, error: 'Forbidden: report ownership or report-view permission required.' }, { status: 403 });
    }

    let saved: any = null;
    try { saved = JSON.parse(report.data); } catch { /* Older rows may be truncated JSON; do not return the raw blob. */ }
    const hasB2BAccess = canViewB2B(auth.roles, auth.permissions);
    if (saved?.canViewB2B && !hasB2BAccess) {
      return NextResponse.json({ success: false, error: 'Forbidden: this report contains B2B-confidential data.' }, { status: 403 });
    }
    if (saved?.filters?.source?.toUpperCase?.().startsWith('B2B_') && !hasB2BAccess) {
      return NextResponse.json({ success: false, error: 'Forbidden: B2B report filter access required.' }, { status: 403 });
    }
    if (Array.isArray(saved?.data) && !hasB2BAccess) {
      saved.data = saved.data.map((application: any) => stripB2BFields(application, false, false));
      saved.canViewB2B = false;
    }

    await logAuditAction(auth, 'VIEW_APPLICATION_REPORT', 'Application', report.id, { format });
    return NextResponse.json({
      success: true,
      data: saved,
      report: { id: report.id, reportType: report.reportType, format: report.format, status: report.status, generatedAt: report.createdAt },
      format,
    });
  } catch (error) {
    console.error('[application-report.download] failed', { error: error instanceof Error ? error.name : 'UnknownError' });
    return NextResponse.json({ success: false, error: 'Application report is temporarily unavailable.' }, { status: 503 });
  }
});
