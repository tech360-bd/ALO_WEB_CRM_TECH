export function getPlatformById(id: string): SocialPlatformDefinition | undefined {
  return SOCIAL_PLATFORMS_REGISTRY.find(p => p.id === id || p.name === id);
}

export function getPlatformsByIds(ids: string[]): SocialPlatformDefinition[] {
  return ids.map(id => getPlatformById(id)).filter(Boolean) as SocialPlatformDefinition[];
}

