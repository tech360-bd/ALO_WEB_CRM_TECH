/**
 * Research timeline planner.
 *
 * This is a *suggested project plan*. It is deliberately separate from official
 * programme deadlines: the planner never invents an official date, and the
 * generated milestones are labelled as planning estimates with configurable
 * durations.
 */

export type TimelineCategory =
  | 'SETUP'
  | 'LITERATURE'
  | 'PROPOSAL'
  | 'SUPERVISION'
  | 'ETHICS'
  | 'DESIGN'
  | 'DATA'
  | 'ANALYSIS'
  | 'THESIS'
  | 'WRITING'
  | 'EXAMINATION';

export interface MilestoneDraft {
  key: string;
  name: string;
  category: TimelineCategory;
  startDate: Date;
  endDate: Date;
  dependsOnKey: string | null;
  notes: string;
  isOfficialDeadline: false;
}

export interface TimelinePlan {
  startDate: Date;
  endDate: Date;
  totalMonths: number;
  mode: 'FULL_TIME' | 'PART_TIME';
  milestones: MilestoneDraft[];
  assumptions: string[];
  warnings: string[];
}

export interface TimelineRequest {
  startDate: Date | string;
  mode: 'FULL_TIME' | 'PART_TIME';
  discipline: 'BUSINESS' | 'ENGINEERING' | 'UNDECIDED';
  methodology?: string;
  totalMonths?: number;
  partTimeMultiplier?: number;
  holidays?: string;
}

function addMonths(date: Date, months: number): Date {
  const result = new Date(date.getTime());
  const targetMonth = result.getMonth() + months;
  const targetDay = result.getDate();
  result.setDate(1);
  result.setMonth(targetMonth);
  const daysInTarget = new Date(result.getFullYear(), result.getMonth() + 1, 0).getDate();
  result.setDate(Math.min(targetDay, daysInTarget));
  return result;
}

const BASE_SEQUENCE: Array<{ key: string; name: string; category: TimelineCategory; share: number; note: string; dependsOn?: string }> = [
  { key: 'topic', name: 'Topic confirmation and scope agreement', category: 'PROPOSAL', share: 0.04, note: 'Confirm the scope with a supervisor. The gap is still provisional at this stage.' },
  { key: 'supervisor', name: 'Supervisor discussions and fit confirmation', category: 'SUPERVISION', share: 0.05, note: 'Record actual replies. A match score is not supervision.' },
  { key: 'proposal', name: 'Proposal refinement against programme requirements', category: 'PROPOSAL', share: 0.08, note: 'Apply the verified word limit and headings independently for each programme.' },
  { key: 'literature', name: 'Documented literature search and review', category: 'LITERATURE', share: 0.14, note: 'Record queries, databases, dates and screening decisions. This is not a systematic review unless the protocol says so.', dependsOn: 'topic' },
  { key: 'ethics', name: 'Ethics and data-access approvals', category: 'ETHICS', share: 0.05, note: 'Apply before data collection. Lab/fieldwork also needs a safety assessment.', dependsOn: 'literature' },
  { key: 'design', name: 'Research design, instruments and pilot', category: 'DESIGN', share: 0.09, note: 'Pilot the instruments and record changes made after the pilot.', dependsOn: 'ethics' },
  { key: 'data', name: 'Data collection or engineering experimentation', category: 'DATA', share: 0.18, note: 'Keep a contemporaneous log and a documented fallback if access changes.', dependsOn: 'design' },
  { key: 'analysis', name: 'Analysis, modelling and validation', category: 'ANALYSIS', share: 0.13, note: 'Pre-specify robustness checks where possible; record deviations.', dependsOn: 'data' },
  { key: 'thesis-plan', name: 'Thesis chapter planning', category: 'THESIS', share: 0.05, note: 'Agree chapter structure and authorship conventions with supervisors.', dependsOn: 'analysis' },
  { key: 'writing', name: 'Writing and revision', category: 'WRITING', share: 0.13, note: 'Build in supervisor turnaround time and institutional review.', dependsOn: 'thesis-plan' },
  { key: 'submission', name: 'Submission, viva preparation and examination', category: 'EXAMINATION', share: 0.06, note: 'Check the official submission and examination regulations; these are not generated by this plan.', dependsOn: 'writing' },
];

export function generateTimeline(request: TimelineRequest): TimelinePlan {
  const start = request.startDate instanceof Date ? request.startDate : new Date(request.startDate);
  if (Number.isNaN(start.getTime())) {
    throw new Error('A valid start date is required; the planner does not invent a start date.');
  }
  const multiplier = request.mode === 'PART_TIME' ? (request.partTimeMultiplier ?? 2) : 1;
  const warnings: string[] = [];
  let totalMonths = request.totalMonths ?? (request.discipline === 'ENGINEERING' ? 42 : 36);
  if (request.mode === 'PART_TIME' && !request.totalMonths) totalMonths = 72;
  if (totalMonths < 12 || totalMonths > 96) {
    warnings.push('The requested duration is outside the 12–96 month range; the plan was generated but should be checked against verified programme rules.');
  }
  totalMonths = Math.max(12, Math.min(96, totalMonths));

  const milestones: MilestoneDraft[] = [];
  let cursor = new Date(start.getTime());
  for (const step of BASE_SEQUENCE) {
    const months = Math.max(1, Math.round(totalMonths * step.share));
    const end = addMonths(cursor, months);
    milestones.push({
      key: step.key,
      name: step.name,
      category: step.category,
      startDate: new Date(cursor.getTime()),
      endDate: end,
      dependsOnKey: step.dependsOn ?? null,
      notes: step.note,
      isOfficialDeadline: false,
    });
    cursor = addMonths(end, 0);
  }

  const assumptions = [
    `Planning duration used: ${totalMonths} months (${request.mode === 'PART_TIME' ? 'part-time' : 'full-time'}).`,
    'Milestone durations are configurable planning estimates, not official university deadlines.',
    request.mode === 'PART_TIME'
      ? 'Part-time plans are stretched, but institutional maximum registration periods still apply.'
      : 'Full-time plans assume continuous registration; suspension or extension periods are not included.',
    'Ethics approval timing varies by programme and must be confirmed.',
    'Supervision response time and reviewer turnaround are not guaranteed.',
  ];
  if (request.holidays) assumptions.push(`Applicant constraint recorded: ${request.holidays}.`);
  if (multiplier !== 1) assumptions.push(`Part-time multiplier applied: ${multiplier}.`);

  return {
    startDate: start,
    endDate: milestones[milestones.length - 1].endDate,
    totalMonths,
    mode: request.mode,
    milestones,
    assumptions,
    warnings,
  };
}

export function criticalPath(plan: TimelinePlan): MilestoneDraft[] {
  const byKey = new Map(plan.milestones.map((milestone) => [milestone.key, milestone]));
  const path: MilestoneDraft[] = [];
  let cursor: MilestoneDraft | undefined = plan.milestones[plan.milestones.length - 1];
  while (cursor) {
    path.unshift(cursor);
    cursor = cursor.dependsOnKey ? byKey.get(cursor.dependsOnKey) : undefined;
  }
  return path;
}
